// Rehearses the static demo using local browser data and Vercel's configured headers.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({channel:'msedge', headless:true});
  try {
    const page = await browser.newPage({viewport:{width:390,height:844}});
    page.setDefaultTimeout(6000);
    const errors = [];
    const requests = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('request', r => requests.push(r.url()));
    const base=process.env.PHARMACY_DEMO_ORIGIN ?? 'http://127.0.0.1:5173';
    const btn = name => page.getByRole('button',{name,exact:true});
    const role = name => page.getByRole('button',{name:new RegExp('^'+name)});
    const link = name => page.getByRole('link',{name,exact:true});
    const wait = locator => locator.waitFor({state:'visible'});
    const show = value => wait(page.getByText(value,{exact:true}));
    const signIn = async name => { await role(name).click(); await wait(btn('تغيير الدور')); };
    const change = async name => { await btn('تغيير الدور').click(); await signIn(name); };
    const saved = () => page.evaluate(() => JSON.parse(localStorage.getItem('pharmacy.demo.data.v1')));
    const checks = async () => page.evaluate(async () => (await window.axe.run(document, {
      runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}
    })).violations.map(item=>[item.id,item.nodes.map(n=>n.target)]));
    const { headers } = require('../front Deploy/pharmacy-web-demo/vercel.json');
    const demoHeaders = Object.fromEntries(headers[0].headers.map(({ key, value }) => [key, value]));
    await page.addInitScript({path:require.resolve('axe-core/axe.min.js')});
    await page.route('**/*', async route => {
      if (route.request().resourceType() !== 'document') return route.continue();
      const response = await route.fetch();
      await route.fulfill({response, headers:{...response.headers(), ...demoHeaders}});
    });
    await page.goto(base);
    assert.equal(await page.locator('.demo-role').count(),4);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390);

    assert.deepEqual(await checks(),[]);
    await btn('English').click();
    assert.equal(await page.locator('html').getAttribute('dir'),'ltr');
    assert.deepEqual(await checks(),[]);
    await btn('العربية').click();
    await signIn('كاشير');
    assert.ok(page.url().endsWith('/pos'));
    assert.equal(await link('المستخدمون').count(),0);
    const scanner = page.getByRole('textbox',{name:'ابحث بالاسم أو امسح الباركود'});
    await wait(page.getByRole('button',{name:/باراسيتامول 500 مجم · علبة/}));
    await scanner.fill('62009901');
    await scanner.press('Enter');
    await btn('تسجيل البيع').click();
    await wait(btn('طباعة الإيصال'));
    const receipt = page.url();
    let data = await saved();
    assert.equal(data.sales.at(-1).totalAmount,32);
    assert.equal(data.batches.find(b=>b.id===11).quantity,17);
    await page.reload();
    await wait(btn('طباعة الإيصال'));
    assert.equal(page.url(),receipt);
    await page.locator('input[name=quantity]').fill('1');
    await page.locator('input[name=reason]').fill('مرتجع تجريبي');
    await page.locator('form').filter({has:page.locator('input[name=reason]')}).getByRole('button').click();
    await wait(page.getByRole('status').filter({hasText:'تم تسجيل رد نقدي'}));
    assert.equal((await saved()).batches.at(-1).isQuarantined,true);

    await link('نقطة البيع').click();
    await wait(page.getByRole('button',{name:/باراسيتامول 500 مجم · علبة/}));
    await scanner.fill('62009901');
    await scanner.press('Enter');
    await page.getByLabel('مبلغ الخصم').fill('10');
    await page.getByLabel('سبب الخصم').fill('عرض تجريبي');
    await btn('طلب اعتماد الخصم').click();
    await wait(page.getByRole('status').filter({hasText:'طلب اعتماد الخصم'}));
    const discountId = (await saved()).approvals.at(-1).id;
    await change('مدير الفرع');
    await link('اعتماد الخصومات').click();
    await page.locator('article').filter({hasText:'طلب #'+discountId}).getByRole('button',{name:'اعتماد الخصم',exact:true}).click();
    await show('معتمد');
    await change('كاشير');
    await btn('تسجيل البيع').click();
    await wait(btn('طباعة الإيصال'));
    assert.equal((await saved()).sales.at(-1).totalAmount,22);

    await change('مسؤول المخزن');
    assert.ok(page.url().endsWith('/transfers'));
    assert.equal(await link('نقطة البيع').count(),0);
    const transfer = page.locator('article').filter({hasText:'#401'});
    await transfer.getByRole('button',{name:'اعتماد',exact:true}).click();
    await wait(transfer.getByText('جاهز للشحن',{exact:false}));
    assert.equal((await saved()).batches.find(b=>b.id===43).reservedQuantity,24);
    await transfer.getByRole('button',{name:'شحن التحويل'}).click();
    await wait(transfer.getByText('قيد النقل',{exact:false}));
    await change('مدير الفرع');
    await link('التحويلات').click();
    await transfer.getByRole('button',{name:'دفعات الشحنة'}).click();
    await transfer.locator('input[name=accepted]').fill('22');
    await transfer.locator('input[name=damaged]').fill('1');
    await transfer.locator('input[name=missing]').fill('1');
    await transfer.locator('input[name=note]').fill('فقد أثناء النقل');
    await transfer.getByRole('button',{name:'تسجيل استلام التحويل'}).click();
    await wait(transfer.getByText('تم الاستلام',{exact:false}));
    data = await saved();
    assert.equal(data.batches.find(b=>b.id===43).quantity,49);
    assert.ok(data.batches.some(b=>b.productId===4 && b.locationId===1 && b.quantity===22));
    await link('المشتريات').click();
    await page.locator('article').filter({hasText:'#301'}).getByRole('button',{name:'استلام دفعة',exact:true}).click();
    await page.locator('input[name=quantity]').fill('10');
    await page.locator('input[name=batchNumber]').fill('DEMO-RECEIPT');
    await page.locator('input[name=expiryDate]').fill(new Date(Date.now()+86400000*90).toISOString().slice(0,10));
    await page.locator('input[name=invoiceNumber]').fill('DEMO-145');
    await btn('تسجيل الاستلام').click();
    await wait(page.getByRole('status').filter({hasText:'تم تسجيل الاستلام'}));
    assert.equal((await saved()).orders.find(o=>o.id===301).lines[0].received,10);
    await link('الجرد').click();
    await btn('اعتماد التسوية').click();
    await show('تم اعتماد التسوية');
    assert.equal((await saved()).batches.find(b=>b.id===21).quantity,19);
    await link('المطابقة').click();
    await btn('عرض المطابقة').click();
    await wait(page.getByRole('heading',{name:'مبيعات بطاقات'}));

    await change('مدير النظام');
    await link('تتبّع الدفعات').click();
    await btn('تتبّع الدفعة').click();
    await wait(page.getByRole('heading',{name:'أرصدة الدفعة RX-2402'}));
    await page.getByLabel('سبب فتح قرار السحب').fill('تحقق جودة تجريبي');
    await btn('فتح قرار السحب').click();
    await show('تم فتح قرار السحب');
    await link('المستخدمون').click();
    await show('ندى حسن');
    const routes = await page.locator('nav a').evaluateAll(nodes => nodes.map(node=>node.getAttribute('href')));
    for (const path of routes) {
      await page.goto(base+path);
      await wait(page.locator('main h1'));
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390,path);
      assert.equal(await page.locator('main [role=alert]').count(),0,path);
    }
    await btn('تغيير الدور').click();
    await btn('استرجاع بيانات الديمو').click();
    await btn('استرجاع البيانات').click();
    assert.equal((await saved()).sales.length,8);
    assert.equal((await saved()).batches.find(b=>b.id===11).quantity,20);
    assert.equal((await saved()).recalls.length,0);
    assert.deepEqual(errors,[]);
    assert.ok(requests.every(url=>url.startsWith(base) && !url.includes('/api/')));
    console.log('PASS mobile login and axe (Arabic/English), four roles, sale/return/reload, cross-role discount and transfer, purchase receipt, stock count, reconciliation, recall, direct routes, reset, zero API requests');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
